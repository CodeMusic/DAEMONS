#!/usr/bin/env python3
"""T-389, T-390 (bible 0.7, Wisdom; the user, 2026-10-08): a MARK and its ROOT together.

Reads `docs/wisdom.json` -- every word of it DRAFT -- and writes three things into the GBA engine:

  1. each of the seven BENCHMARKS' text.inc: the leader's lines after the win, without the paired understanding and
     with it, the union PLUGIN handed over, and what it does;
  2. each BENCHMARK's scripts.inc: `<Map>_EventScript_Wisdom`, which the leader's talk-again branch goes to (that one
     `goto` is written by hand in each gym, and this tool refuses to run if it is missing). Without the
     understanding: what the MARK taught and where to come back understanding. With it: the two together, and the
     PLUGIN, once;
  3. `src/data/wisdom.h`: the seven insights -- the NOTEBOOK's INSIGHT section (notebook.c) and the line that arrives
     on the first step after a MARK and its understanding are both held (field_control_avatar.c);
     T-410: each pair's two balances, shown once both are held -- the MARK's on the USER card's BENCHMARKS page
     (wrapped here to CARD_W, paged CARD_PAGE lines at a time), the ROOT's in its understanding's GUIDE margin (book_reader.c
     reflows it); T-411: the last note, which arrives once all seven insights have, and is filed last under INSIGHT.

Every box is wrapped to the message box's 208px in the game's own font; a line that will not fit stops the run.
The blocks it owns sit between `@ BEGIN gbawisdom` and `@ END gbawisdom`, so a rerun replaces them and nothing else.

  python3 tools/gbawisdom.py            # report what would change
  python3 tools/gbawisdom.py --write
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from genguide import width  # noqa: E402  (the game's font, read from the engine)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GBA = os.path.join(ROOT, "engineGba")
SRC = os.path.join(ROOT, "docs", "wisdom.json")
HEADER = os.path.join(GBA, "src", "data", "wisdom.h")
BOX = 208
CARD_W, CARD_PAGE, CARD_PAGES = 114, 4, 2   # T-410: the BENCHMARKS page's certify lines (trainer_card.c): 114px, four a page
BEGIN, END = "@ BEGIN gbawisdom", "@ END gbawisdom"
GIVE = ("Take this.", "Here!")


def wrap(text, w=BOX):
    lines, cur = [], ""
    for word in text.split():
        cand = (cur + " " + word).strip()
        if width(cand) <= w:
            cur = cand
        else:
            if not cur:
                sys.exit("gbawisdom: %r is wider than %dpx on its own" % (word, w))
            lines.append(cur)
            cur = word
    lines.append(cur)
    return lines


def box_string(paragraphs):
    """Paragraphs -> one message: \\n then \\l within a paragraph, \\p between."""
    out = []
    for para in paragraphs:
        ls = wrap(para)
        out.append(ls[0] + "".join(("\\n" if i == 1 else "\\l") + l for i, l in enumerate(ls[1:], 1)))
    return "\\p".join(out)


def asm_string(label, paragraphs):
    s = box_string(paragraphs)
    return "%s::\n\t.string \"%s$\"\n" % (label, s)


def split_give(paras):
    """The 'with' lines end by handing the PLUGIN over; said again after it is given, that part is left off."""
    again = list(paras)
    last = again[-1]
    for g in GIVE:
        if last == g:
            again.pop()
        elif last.endswith(" " + g):
            again[-1] = last[: -len(g) - 1]
    return again


def gym_blocks(p):
    m = p["map"]
    text = [
        "%s -- T-389, GENERATED by tools/gbawisdom.py from docs/wisdom.json. Every word DRAFT." % BEGIN,
        asm_string("%s_Text_WisdomWithout" % m, p["without"]),
        asm_string("%s_Text_WisdomWith" % m, p["with"]),
        asm_string("%s_Text_WisdomAgain" % m, split_give(p["with"])),
        "%s_Text_ReceivedUnion::\n\t.string \"{PLAYER} received %s from\\n%s.$\"\n" % (m, p["plugin_name"], p["leader"]),
        asm_string("%s_Text_ExplainUnion" % m, p["explain"]),
        asm_string("%s_Text_WisdomNoRoom" % m, ["Make room in your TOOLKIT, and come back."]),
        END,
    ]
    script = "\n".join([
        "%s -- T-389, GENERATED by tools/gbawisdom.py from docs/wisdom.json." % BEGIN,
        "@ After the win: without the understanding, what the MARK taught and where to come back understanding;",
        "@ with it, the two together and the union PLUGIN, once (bible 0.7, Wisdom).",
        "%s_EventScript_Wisdom::" % m,
        "\tgoto_if_unset %s, %s_EventScript_WisdomNotYet" % (p["root"], m),
        "\tgoto_if_set %s, %s_EventScript_WisdomAgain" % (p["given"], m),
        "\tmsgbox %s_Text_WisdomWith" % m,
        "\tcheckitemspace %s" % p["plugin"],
        "\tgoto_if_eq VAR_RESULT, FALSE, %s_EventScript_WisdomNoRoom" % m,
        "\tgiveitem_msg %s_Text_ReceivedUnion, %s" % (m, p["plugin"]),
        "\tsetflag %s" % p["given"],
        "\tmsgbox %s_Text_ExplainUnion" % m,
        "\trelease",
        "\tend",
        "",
        "%s_EventScript_WisdomAgain::" % m,
        "\tmsgbox %s_Text_WisdomAgain" % m,
        "\trelease",
        "\tend",
        "",
        "%s_EventScript_WisdomNotYet::" % m,
        "\tmsgbox %s_Text_WisdomWithout" % m,
        "\trelease",
        "\tend",
        "",
        "%s_EventScript_WisdomNoRoom::" % m,
        "\tmsgbox %s_Text_WisdomNoRoom" % m,
        "\trelease",
        "\tend",
        END,
    ])
    return "\n".join(text) + "\n", script + "\n"


def c_text(s):
    return s.replace('"', '\\"')


def card_string(text):
    """T-410: a MARK's balance on the BENCHMARKS page -- the approved words, rewrapped to the certify lines' width, four
    lines a page (\\n between lines, \\p between pages), and never more than two pages."""
    ls = wrap(text, CARD_W)
    pages = [ls[i:i + CARD_PAGE] for i in range(0, len(ls), CARD_PAGE)]
    if len(pages) > CARD_PAGES:
        sys.exit("gbawisdom: %r needs %d pages on the BENCHMARKS page, which turns %d" % (text[:40], len(pages), CARD_PAGES))
    return "\\p".join("\\n".join(pg) for pg in pages)


def header(doc):
    out = ["// GENERATED by DAEMONS tools/gbawisdom.py from docs/wisdom.json -- do not edit by hand.",
           "// T-390 (bible 0.7, Wisdom): the seven insights, one for each MARK and its understanding held together.",
           "// T-410: each pair's two balances; T-411: the last note. Every word DRAFT. Included once, by notebook.c.",
           "#ifndef GUARD_DATA_WISDOM_H", "#define GUARD_DATA_WISDOM_H", ""]
    entries, pairs = [], []
    for p in doc["pairs"]:
        v = p["virtue"].capitalize()
        ins = wrap(p["insight"], 200)
        arrival = [doc["arrival"][0], doc["arrival"][1].replace("{INSIGHT}", p["insight"]), doc["arrival"][2]]
        out.append('static const u8 sInsightTitle_%s[] = _("%s");' % (v, p["virtue"]))
        out.append('static const u8 sInsightText_%s[] = _("%s");' % (v, c_text(" ".join(ins))))
        out.append('static const u8 sInsightArrival_%s[] = _("%s");' % (v, c_text(box_string(arrival))))
        out.append('static const u8 sMarkBalance_%s[] = _("%s");' % (v, c_text(card_string(p["mark_balance"]))))
        out.append('static const u8 sRootBalance_%s[] = _("%s");' % (v, c_text(" ".join(p["root_balance"].split()))))
        entries.append("    { NB_INSIGHT, NB_KIND_TEXT, 0, %s, 0, sInsightTitle_%s, sInsightText_%s }," % (p["insight_flag"], v, v))
        pairs.append("    { %s, %s, %s, sInsightArrival_%s, sMarkBalance_%s, sRootBalance_%s }," % (p["badge"], p["root"], p["insight_flag"], v, v, v))
    last = doc["last"]
    arrival = [doc["arrival"][0], doc["arrival"][1].replace("{INSIGHT}", last["insight"]), doc["arrival"][2]]
    out.append('static const u8 sInsightTitle_Last[] = _("%s");' % c_text(last["title"]))
    out.append('static const u8 sInsightText_Last[] = _("%s");' % c_text(" ".join(wrap(last["insight"], 200))))
    quoted = box_string(arrival)
    if last.get("lines"):        # the draft's own lines, kept where every one fits the box with its quotes
        if " ".join(last["lines"]) != last["insight"]:
            sys.exit("gbawisdom: the last note's lines are not its words")
        q = list(last["lines"])
        q[0], q[-1] = "“" + q[0], q[-1] + "”"
        if all(width(l) <= BOX for l in q):
            quoted = "\\p".join([doc["arrival"][0], q[0] + "".join(("\\n" if i == 1 else "\\l") + l for i, l in enumerate(q[1:], 1)), doc["arrival"][2]])
    out.append('static const u8 sInsightArrival_Last[] = _("%s");' % c_text(quoted))
    entries.append("    { NB_INSIGHT, NB_KIND_TEXT, 0, %s, 0, sInsightTitle_Last, sInsightText_Last }," % last["flag"])
    out += ["", "//  The INSIGHT section's entries, in the MARKS' order (notebook.c rule 2: the authored order, never the order found),",
            "//  and T-411's last note after them.",
            "#define NB_INSIGHT_ENTRIES \\"]
    out += [e + " \\" for e in entries]
    out += ["", "", "//  What makes each arrive: the MARK, the understanding, and the flag that says it has; T-410, the two balances.",
            "struct WisdomPair { u16 mark; u16 root; u16 insight; const u8 *arrival; const u8 *markBalance; const u8 *rootBalance; };",
            "static const struct WisdomPair sWisdomPairs[] =", "{"] + pairs + ["};", "",
            "//  T-411: the last note -- its flag, and what is said when it arrives (once every insight above has).",
            "#define WISDOM_LAST_FLAG %s" % last["flag"],
            "#define WISDOM_LAST_ARRIVAL sInsightArrival_Last", "", "#endif // GUARD_DATA_WISDOM_H", ""]
    return "\n".join(out)


def replace_block(path, block):
    s = open(path).read()
    if BEGIN in s:
        a = s.index(BEGIN)
        b = s.index(END, a) + len(END)
        new = s[:a] + block.rstrip("\n") + s[b:]
    else:
        new = s.rstrip("\n") + "\n\n" + block
    return s, new


def main():
    write = "--write" in sys.argv
    doc = json.load(open(SRC))
    changes = []
    for p in doc["pairs"]:
        text, script = gym_blocks(p)
        sp = os.path.join(GBA, "data", "maps", p["map"], "scripts.inc")
        if "goto %s_EventScript_Wisdom\n" % p["map"] not in open(sp).read():
            sys.exit("gbawisdom: %s's talk-again branch does not go to %s_EventScript_Wisdom -- add that goto by hand"
                     % (p["leader"], p["map"]))
        for path, block in ((os.path.join(GBA, "data", "maps", p["map"], "text.inc"), text), (sp, script)):
            old, new = replace_block(path, block)
            if old != new:
                changes.append((path, new))
    h = header(doc)
    if not os.path.exists(HEADER) or open(HEADER).read() != h:
        changes.append((HEADER, h))
    for path, new in changes:
        print("  %s %s" % ("wrote" if write else "would write", os.path.relpath(path, GBA)))
        if write:
            open(path, "w").write(new)
    if not changes:
        print("  gbawisdom: everything matches docs/wisdom.json")


if __name__ == "__main__":
    main()

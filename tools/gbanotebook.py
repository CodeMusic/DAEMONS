#!/usr/bin/env python3
"""T-403 (the user, 2026-10-15): a NOTEBOOK page says where it was found, what it is, and whether it has been read.

    python3 tools/gbanotebook.py            # report what would change
    python3 tools/gbanotebook.py --write    # engineGba/src/data/notebook_notes.h

Reads `docs/notebook_notes.json` -- one row per NOTEBOOK entry, keyed by the flag that files it -- and writes the
table notebook.c looks each entry up in:

  seen   its SEEN flag, FLAG_NOTEBOOK_SEEN_0 + seen (flags.h) -- and from 64 up, FLAG_NOTEBOOK_SEEN_64 + seen - 64,
         the second block (T-417 P2: the first filled at 61; notebook.c's SeenFlag spills). PERMANENT: a new entry
         takes the next number and a number is never reused, or an old save's marks would move to other pages.
  map    the map it was found on (its folder in data/maps); R in the NOTEBOOK opens the TOWN MAP there. None for a
         page with no place (the INSIGHTs: they arrive, they are not found).
  about  one line under the list, DRAFT. It says what the thing IS -- never what it means (craft rule 1).

A row with "placed" is one of tools/gbadocs.py's documents: its map is that tool's spot, and its words live with the
document's own in docs/private/notebook_docs.json ("about"), which is gitignored. Without that file the placed rows
keep the descriptions the header already has, so a fresh clone builds the same ROM.

Every description is measured in the game's own font against the message box's 208px; one that will not fit stops
the run.
"""
import io, json, os, re, sys, contextlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GBA = os.path.join(ROOT, "engineGba")
OUT = os.path.join(GBA, "src", "data", "notebook_notes.h")
WRITE = "--write" in sys.argv
PRIVATE = os.path.join(ROOT, "docs", "private", "notebook_docs.json")
SEEN_COUNT = 128         # FLAG_NOTEBOOK_SEEN_0 .. +63, then FLAG_NOTEBOOK_SEEN_64 .. +63 (flags.h; T-417 P2)
BOX = 208

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
argv, sys.argv = sys.argv, [sys.argv[0]]          # gbadocs reads --write at import (engine.md)
with contextlib.redirect_stdout(io.StringIO()):
    import gbadocs
    import genguide
sys.argv = argv


def map_const(folder):
    path = os.path.join(GBA, "data", "maps", folder, "map.json")
    if not os.path.exists(path):
        sys.exit("gbanotebook: no map %s" % folder)
    return json.load(open(path))["id"]


def c_string(s):
    return '_("%s")' % s.replace('"', '\\"')


def main():
    genguide.load_font()
    notes = json.load(open(os.path.join(ROOT, "docs", "notebook_notes.json")))["notes"]
    spots = {k: s for k, s in gbadocs.DOCS}
    private = json.load(open(PRIVATE)) if os.path.exists(PRIVATE) else None
    old = open(OUT).read() if os.path.exists(OUT) else ""
    kept = dict(re.findall(r'static const u8 sNoteAbout_(\w+)\[\] = _\("((?:[^"\\]|\\.)*)"\);', old))
    seen, rows, bad = set(), [], []
    for flag, r in notes.items():
        n = r["seen"]
        if n in seen or not 0 <= n < SEEN_COUNT:
            bad.append("%s: seen %d is used twice or out of range" % (flag, n))
        seen.add(n)
        if "placed" in r:
            key = r["placed"]
            spot = spots.get(key)
            mp = spot[1] if spot else None
            about = (private.get(key, {}).get("about") if private else None) or kept.get(flag[len("FLAG_"):], "").replace('\\"', '"')
            if spot and not about:
                bad.append("%s: placed, and no description in %s" % (flag, PRIVATE))
        else:
            mp, about = r.get("map"), r.get("about") or ""
        if about and genguide.width(about) > BOX:
            bad.append("%s: %dpx in the %dpx box: %s" % (flag, genguide.width(about), BOX, about))
        rows.append((flag, n, map_const(mp) if mp else None, about))
    if bad:
        sys.exit("gbanotebook:\n  " + "\n  ".join(bad))
    out = ["//  GENERATED by DAEMONS tools/gbanotebook.py (T-403) from docs/notebook_notes.json -- edit that, not this.",
           "//  Each NOTEBOOK entry, by the flag that files it: its SEEN flag (FLAG_NOTEBOOK_SEEN_0 + seen), the map it",
           "//  was found on (MAP_UNDEFINED: nowhere -- it arrived), and its one line under the list. Every line DRAFT.", ""]
    for flag, n, mp, about in rows:
        if about:
            out.append("static const u8 sNoteAbout_%s[] = %s;" % (flag[len("FLAG_"):], c_string(about)))
    out += ["", "static const struct NotebookNote sNotebookNotes[] =", "{"]
    for flag, n, mp, about in rows:
        out.append("    { %s, %d, %s, %s }," % (flag, n, mp or "MAP_UNDEFINED", "sNoteAbout_%s" % flag[len("FLAG_"):] if about else "NULL"))
    out += ["};", ""]
    text = "\n".join(out)
    for flag, n, mp, about in rows:
        print("  %2d %-36s %-36s %s" % (n, flag, mp or "-", about))
    if text == old:
        print("  notebook_notes.h is current")
    elif not WRITE:
        print("  notebook_notes.h would change; pass --write")
    else:
        open(OUT, "w").write(text)
        print("  written  src/data/notebook_notes.h")


if __name__ == "__main__":
    main()

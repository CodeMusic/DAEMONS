def matrix(url):
    import qrcode
    q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_L, border=0)
    q.add_data(url)
    q.make(fit=True)
    return q.get_matrix()


def header():
    out = ["//  GENERATED by tools/gbaqr.py (T-315) -- edit that, not this.",
           "//  Each code: its size in modules, then one row after another, eight modules a byte, high bit first.", ""]
    for name, url in CODES:
        m = matrix(url)
        n = len(m)
        data = [n]
        for row in m:
            for b in range(0, n, 8):
                v = 0
                for k in range(8):
                    if b + k < n and row[b + k]:
                        v |= 0x80 >> k
                data.append(v)
        out.append("//  %s" % url)
        body = ", ".join("0x%02X" % v for v in data)
        out.append("static const u8 sQr_%s[] = { %s };" % (name, body))
        out.append("")
    out.append("static const u8 *const sQrCodes[] = { NULL, %s };" % ", ".join("sQr_%s" % n for n, _ in CODES))
    out.append("")
    return "\n".join(out)


def enum():
    import re
    names = ["BOOK_QR_NONE"] + ["BOOK_QR_" + re.sub(r"(?<=[a-z])(?=[A-Z])", "_", n).upper() for n, _ in CODES]
    return "\n".join(["#ifndef GUARD_CONSTANTS_BOOK_QR_H", "#define GUARD_CONSTANTS_BOOK_QR_H", "",
                      "//  GENERATED by tools/gbaqr.py (T-315, T-402) -- edit that, not this. One per code in sQrCodes.", ""]
                     + ["#define %-24s %d" % (n, i) for i, n in enumerate(names)] + ["", "#endif", ""])


def main():
    for name, url in CODES:
        print("  %-13s %2d modules  %s" % (name, len(matrix(url)), url))
    for path, text in ((OUT, header()), (ENUM, enum())):
        rel = os.path.relpath(path, os.path.join(ROOT, "engineGba"))
        old = open(path).read() if os.path.exists(path) else None
        if old == text:
            print("  %s is current" % rel)
        elif not WRITE:
            print("  %s would change; pass --write" % rel)
        else:
            open(path, "w").write(text)
            print("  written  %s" % rel)


if __name__ == "__main__":
    main()

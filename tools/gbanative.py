#!/usr/bin/env python3
"""What each daemon is NATIVE to, for the INDEX area page (T-407).

    python3 tools/gbanative.py            # report
    python3 tools/gbanative.py --write    # engineGba/src/data/daemons_native.h

The user, 2026-10-16: the INDEX says what a daemon is native to -- its region, its edition, its hour and its season
-- in the box vanilla used for the size comparison, under the heading NATIVE. Read from every wild table
(src/data/wild_encounters.json, day and night) and the season and hour rows (tools/gbashifts.py), so it can never
disagree with where a daemon is actually met. A daemon met only in a grove shows "A GROVE" until seen, then that
grove's universe without its THE (T-408, tools/gbanexusmap.py); one met only in THE NEXUS shows THE NEXUS.

One u16 a species, in ROM:
  bit 0 GAMUT, bit 1 THE MARGINS            (the mainland, the islands)
  bit 2 CONTENT, bit 3 CONTEXT              (FireRed's tables, LeafGreen's)
  bits 4-7  seasons, SEASON_* order         (include/daemons_time.h)
  bits 8-11 watches, WATCH_* order
  bits 12-15 0, a grove (1-14, gbagrove.GROVES order), or 15 THE NEXUS -- only when every home is that one place
  bits 16-20 RAIN STORM SNOW FOG WIND        (DAEMONS_SKY_* from RAIN) -- only when every home is a weather row
                                            (T-415 phase 2, tools/gbashifts.py's WEATHER): the INDEX says "IN RAIN"
A species no wild table names is 0. The table is u32 since T-415 phase 2 (the u16 was full).
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gbashifts                                    # noqa: E402
import gbagrove                                     # noqa: E402
import gbanexusmap                                  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GBA = os.path.join(ROOT, "engineGba")
OUT = os.path.join(GBA, "src/data/daemons_native.h")
ISLANDS = ("ONE_ISLAND", "TWO_ISLAND", "THREE_ISLAND", "FOUR_ISLAND", "FIVE_ISLAND", "SIX_ISLAND", "SEVEN_ISLAND",
           "MT_EMBER")                              # the plan_global_index.py prefixes
SEASONS, WATCHES, SKIES = gbashifts.SEASONS, gbashifts.WATCHES, gbashifts.SKIES
NEXUS = 15


def map_ids():
    out = {}
    for g in gbagrove.GROVES:
        out[json.load(open(os.path.join(GBA, "data/maps", g["name"], "map.json")))["id"]] = g["name"]
    return out


def homes():
    """{species: set of (edition 0|1, region 0|1, place, season, watch, sky)} -- sky None but in a weather row."""
    wild = json.load(open(os.path.join(GBA, "src/data/wild_encounters.json")))["wild_encounter_groups"][0]["encounters"]
    groves = map_ids()
    nights = {(e["map"], "LeafGreen" in e["base_label"]) for e in wild if e["base_label"].endswith("_Night")}
    out = {}

    def add(sp, ed, mp, seasons, watches, skies=(None,)):
        place = groves.get(mp) or ("NEXUS" if mp == "MAP_NEXUS" else None)
        region = 1 if any(p in mp for p in ISLANDS) else 0
        for s in seasons:
            for w in watches:
                for k in skies:
                    out.setdefault(sp, set()).add((ed, region, place, s, w, k))

    for e in wild:
        label = e["base_label"]
        ed = 1 if "LeafGreen" in label else 0 if "FireRed" in label else None
        eds = (0, 1) if ed is None else (ed,)
        night = label.endswith("_Night")
        watches = ["NIGHT"] if night else ([w for w in WATCHES if w != "NIGHT"]
                                           if (e["map"], ed == 1) in nights else WATCHES)
        for kind in ("land_mons", "water_mons", "rock_smash_mons", "fishing_mons"):
            for m in (e.get(kind) or {}).get("mons", []):
                for d in eds:
                    add(m["species"], d, e["map"], SEASONS, watches)
    names = gbashifts.by_name()
    natural = gbashifts.sky_seasons()   # a weather row: the seasons its weather is drawn in, not every season it can fire
    for ed, mp, _slot, (seasons, watches), sp, _name, skies in gbashifts.rows(names):
        if sp not in gbashifts.LEFT_OUT:
            if skies:
                seasons = [s for s in seasons if any(s in natural[k] for k in skies)]
            add(sp, ed, mp, seasons, watches, skies or (None,))
    return out


def pack(h):
    v = 0
    for ed, region, place, s, w, _k in h:
        v |= 1 << region | 1 << (2 + ed) | 1 << (4 + SEASONS.index(s)) | 1 << (8 + WATCHES.index(w))
    skies = {k for *_, k in h}
    if None not in skies:   # T-415 phase 2: met only in weather
        for k in skies:
            v |= 1 << (16 + SKIES.index(k) - 1)
    places = {place for _, _, place, _, _, _ in h}
    if len(places) == 1 and None not in places:
        (place,) = places
        v |= (NEXUS if place == "NEXUS" else 1 + [g["name"] for g in gbagrove.GROVES].index(place)) << 12
    return v


def render(table):
    groves = [g["name"] for g in gbagrove.GROVES]
    lines = ["// Generated by tools/gbanative.py -- do not edit; run it with --write (T-407, the user 2026-10-16).",
             "// What each daemon is NATIVE to: bit 0 GAMUT, 1 THE MARGINS, 2 CONTENT, 3 CONTEXT, 4-7 seasons (SEASON_*),",
             "// 8-11 watches (WATCH_*), 12-15 a grove (1-14) or THE NEXUS (15) when that is its only home, 16-20 RAIN STORM",
             "// SNOW FOG WIND when it is met only in those (T-415 phase 2). 0: not wild.",
             "static const u32 sDaemonsNative[NUM_SPECIES] = {"]
    for sp in sorted(table, key=lambda s: s):
        lines.append("    [%s] = 0x%0*X," % (sp, 6 if table[sp] >> 16 else 4, table[sp]))
    lines += ["};", ""]
    #  One array a name: agbcc will not take _("...") inside a pointer array's braces.
    names = [gbanexusmap.UNIVERSES[g][0].replace("THE ", "", 1) for g in groves]   # 80px of FONT_SMALL: no THE
    for k, n in enumerate(names, 1):
        lines.append('static const u8 sDaemonsNativeGrove%d[] = _("%s");' % (k, n))
    lines.append('static const u8 sDaemonsNativeNexus[] = _("THE NEXUS");')
    lines += ["", "static const u8 *const sDaemonsNativeGrove[] = {", "    NULL,"]
    lines += ["    sDaemonsNativeGrove%d," % k for k in range(1, len(names) + 1)]
    lines += ["    [%d] = sDaemonsNativeNexus," % NEXUS, "};", ""]
    return "\n".join(lines)


def main():
    table = {sp: pack(h) for sp, h in homes().items() if sp != "SPECIES_NONE"}
    text = render(table)
    old = open(OUT).read() if os.path.exists(OUT) else None
    grove = sum(1 for v in table.values() if v >> 12 & 15)
    weather = sum(1 for v in table.values() if v >> 16)
    one_ed = sum(1 for v in table.values() if (v >> 2 & 3) in (1, 2))
    hour = sum(1 for v in table.values() if (v >> 8 & 15) != 15)
    season = sum(1 for v in table.values() if (v >> 4 & 15) != 15)
    print("  %d wild species: %d grove or NEXUS only, %d weather only, %d one edition, %d keep hours, %d keep seasons -- %s"
          % (len(table), grove, weather, one_ed, hour, season,
             "unchanged" if old == text else ("written" if "--write" in sys.argv else "would write")))
    if "--write" in sys.argv and old != text:
        open(OUT, "w").write(text)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""T-18 P1: the follower's colours -- each daemon's party icon in its own TYPE colours (invariant 5).

    python3 tools/gbafollowerpal.py            # report: how many palettes, which fell back, what would change
    python3 tools/gbafollowerpal.py --write    # write engineGba/src/data/follower_palettes.h

The follower draws the lead's party icon (graphics/pokemon/*/icon.png), and the icons are drawn in one of three SHARED
palettes (gMonIconPaletteIndices), which carry no type: derive_icon() in gbasprite.py says why. The follower has an
OBJ palette slot of its own, so it can keep the rule the party menu cannot. Its pixels do not change -- only what each
index means: every colour of the icon's shared palette is replaced by the NEAREST colour of the daemon's own front
palette (normal.pal, the 9.4 type ramp with its streaks), by squared RGB distance. Index 0 stays transparent.
This is the remap the plan's mock-up showed (follower_typecolour.png, 2026-10-20) and the user chose (option b).

One 16-colour palette per icon species (gMonIconTable's order, the UNOWN letters included), ~14 KB of ROM. An icon
whose folder has no normal.pal (the EGG, the question mark) keeps its shared palette; the report names them.
daemons_follower.c greys it by friendship (T-424's Saturation_ApplyToBuffer) after this.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GBA = os.path.join(ROOT, "engineGba")
OUT = os.path.join(GBA, "src", "data", "follower_palettes.h")


def read_pal(path):
    lines = open(path, encoding="utf-8", errors="ignore").read().split()
    # JASC-PAL / 0100 / 16 / r g b ...
    n = int(lines[2])
    vals = [int(v) for v in lines[3:3 + n * 3]]
    return [tuple(vals[i * 3:i * 3 + 3]) for i in range(n)]


def to15(c):
    r, g, b = c
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def icon_species():
    """[(SPECIES_X, icon symbol)] in gMonIconTable's order, and {symbol: icon.4bpp path}."""
    src = open(os.path.join(GBA, "src", "pokemon_icon.c"), encoding="utf-8").read()
    table = src.split("const u8 *const gMonIconTable[] = {", 1)[1].split("};", 1)[0]
    rows = re.findall(r"\[(SPECIES_\w+)\]\s*=\s*(gMonIcon_\w+)", table)
    idx = src.split("const u8 gMonIconPaletteIndices[] = {", 1)[1].split("};", 1)[0]
    palidx = dict(re.findall(r"\[(SPECIES_\w+)\]\s*=\s*(\d+)", idx))
    gfx = open(os.path.join(GBA, "src", "data", "graphics", "pokemon.h"), encoding="utf-8").read()
    paths = dict(re.findall(r"const u8 (gMonIcon_\w+)\[\]\s*=\s*INCBIN_U8\(\s*\"([^\"]+)\"", gfx))
    return rows, palidx, paths


def front_pal_for(icon_path):
    """normal.pal beside the icon, or in the folder above (the UNOWN letters share UNOWN's)."""
    d = os.path.dirname(os.path.join(GBA, icon_path))
    for cand in (d, os.path.dirname(d)):
        p = os.path.join(cand, "normal.pal")
        if os.path.exists(p) and os.path.basename(cand) != "pokemon":
            return p
    return None


def remap(shared, front):
    fc = front[1:16]
    out = [shared[0]]
    for c in shared[1:16]:
        out.append(min(fc, key=lambda d: sum((a - b) ** 2 for a, b in zip(c, d))))
    return out


def build():
    rows, palidx, paths = icon_species()
    shared = [read_pal(os.path.join(GBA, "graphics", "pokemon", "icon_palettes", "icon_palette_%d.pal" % i))
              for i in range(3)]
    entries, fell_back = [], []
    for sp, sym in rows:
        base = shared[int(palidx.get(sp, 0))]
        path = paths.get(sym)
        fp = front_pal_for(path) if path else None
        if fp:
            pal = remap(base, read_pal(fp))
        else:
            pal = base
            fell_back.append(sp)
        entries.append((sp, pal))
    return entries, fell_back


def render(entries):
    out = ["//  GENERATED by DAEMONS tools/gbafollowerpal.py -- do not edit. T-18 P1: each icon in its own TYPE colours,",
           "//  every colour of its shared icon palette replaced by the nearest of its front palette (normal.pal).",
           "//  Indexed by ICON species (GetIconSpecies), as gMonIconTable is.",
           "",
           "static const u16 sFollowerPalettes[][16] = {"]
    for sp, pal in entries:
        out.append("    [%s] = {%s}," % (sp, ", ".join("0x%04X" % to15(c) for c in pal)))
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    entries, fell_back = build()
    text = render(entries)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    print("  %d icon palettes, %d bytes of ROM; %d keep the shared palette (%s)"
          % (len(entries), len(entries) * 32, len(fell_back), ", ".join(fell_back)))
    if old == text:
        print("  follower_palettes.h is current")
        return 0
    if "--write" in sys.argv:
        open(OUT, "w", encoding="utf-8").write(text)
        print("  wrote %s" % os.path.relpath(OUT, ROOT))
    else:
        print("  follower_palettes.h would change (%s) -- --write to write it" % ("new" if old is None else "differs"))
    return 0


if __name__ == "__main__":
    sys.exit(main())

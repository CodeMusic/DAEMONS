#!/usr/bin/env python3
"""T-412 (the user, 2026-10-16; approved 2026-10-18): the NOTEBOOK's DREAM LOG -- YOUR DREAMS.

    python3 tools/gbadreamlog.py            # report: every line measured, and whether the header is current
    python3 tools/gbadreamlog.py --write    # engineGba/src/data/dream_log.h

Reads `docs/dream_log.json` -- every word DRAFT -- and writes the table notebook.c files the dreams from and says them
from (Daemons_TryDreamArrives): each dream's flag, the milestone it follows (one flag, or two that must both be held),
its NOTEBOOK title and its words.

It holds the words to the draft's own shape and refuses what would break it:
  - a box keeps the draft's own lines wherever each fits the 208px message box; a box with a line too wide is
    rewrapped (words unchanged) and reported; a single word wider than the box stops the run;
  - a title is the dream's own opening words in capitals, as many whole words as fit TITLE_W -- no new words, and
    never a number (the lock's rule: nothing in a dream counts, numbers or paces anything);
  - every dream fits gStringVar4 (1000 bytes) with the line said before it.
"""
import io, contextlib, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GBA = os.path.join(ROOT, "engineGba")
SRC = os.path.join(ROOT, "docs", "dream_log.json")
OUT = os.path.join(GBA, "src", "data", "dream_log.h")
WRITE = "--write" in sys.argv
BOX = 208
TITLE_W = 130      # the NOTEBOOK's list grows to its widest title; this keeps it the width the other sections use

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
argv, sys.argv = sys.argv, [sys.argv[0]]
with contextlib.redirect_stdout(io.StringIO()):
    from genguide import width   # noqa: E402  (the game's font, read from the engine)
sys.argv = argv


def wrap(text, w=BOX):
    lines, cur = [], ""
    for word in text.split():
        cand = (cur + " " + word).strip()
        if width(cand) <= w:
            cur = cand
        else:
            if not cur:
                sys.exit("gbadreamlog: %r is wider than %dpx on its own" % (word, w))
            lines.append(cur)
            cur = word
    lines.append(cur)
    return lines


def box_lines(box, key, notes):
    if all(width(l) <= BOX for l in box):
        return box
    new = wrap(" ".join(box))
    notes.append("%s: a line was wider than %dpx, so the box is rewrapped: %s" % (key, BOX, " / ".join(new)))
    return new


SMALL = {"A", "AN", "THE", "MY", "ITS", "INTO", "IN", "OF", "ON", "TO", "AND", "AT"}


def title(boxes):
    """The opening words that fit TITLE_W, cut at the first comma or full stop among them; failing that, without the
    little words a cut phrase would end on."""
    taken = []
    for word in " ".join(boxes[0]).upper().split():
        if width(" ".join(taken + [word])) > TITLE_W:
            break
        taken.append(word)
        if word[-1] in ".,:;":
            return " ".join(taken).rstrip(".,:;")
    while len(taken) > 1 and taken[-1] in SMALL:
        taken.pop()
    return " ".join(taken)


def c(s):
    return s.replace('"', '\\"')


def main():
    doc = json.load(open(SRC, encoding="utf-8"))
    notes, rows = [], []
    for d in doc["dreams"]:
        boxes = [box_lines(b, d["key"], notes) for b in d["boxes"]]
        text = "\\p".join(b[0] + "".join(("\\n" if i == 1 else "\\l") + l for i, l in enumerate(b[1:], 1)) for b in boxes)
        t = title(boxes)
        if any(ch.isdigit() for ch in t + text):
            sys.exit("gbadreamlog: %s carries a digit -- a dream never numbers anything" % d["key"])
        if len(doc["line"]) + 2 + len(text) >= 1000:
            sys.exit("gbadreamlog: %s does not fit gStringVar4" % d["key"])
        needs = d["needs"] + [d["needs"][0]] * (2 - len(d["needs"]))
        rows.append((d, t, text, needs, boxes))
    out = ["// GENERATED by DAEMONS tools/gbadreamlog.py from docs/dream_log.json -- do not edit by hand.",
           "// T-412 (the user, 2026-10-16; approved 2026-10-18): the DREAM LOG's YOUR DREAMS. Every word DRAFT.",
           "// Included once, by notebook.c.",
           "#ifndef GUARD_DATA_DREAM_LOG_H", "#define GUARD_DATA_DREAM_LOG_H", "",
           'static const u8 sSection_DreamLog[] = _("%s");' % c(doc["section"]),
           'static const u8 sDreamLine[] = _("%s");' % c(doc["line"]), ""]
    for d, t, text, needs, boxes in rows:
        out.append('static const u8 sDreamTitle_%s[] = _("%s");' % (d["key"].capitalize(), c(t)))
        out.append('static const u8 sDreamText_%s[] = _("%s");' % (d["key"].capitalize(), c(text)))
    out += ["", "//  The DREAM LOG's entries, in the draft's order (notebook.c rule 2: the authored order, never the order dreamt).",
            "#define NB_DREAM_ENTRIES \\"]
    out += ["    { NB_DREAM_LOG, NB_KIND_TEXT, 0, %s, 0, sDreamTitle_%s, sDreamText_%s }, \\"
            % (d["flag"], d["key"].capitalize(), d["key"].capitalize()) for d, t, text, needs, boxes in rows]
    out += ["", "", "//  What each follows -- both flags held (one twice when it follows one) -- and the flag that says it was dreamt.",
            "//  When several wait, they come in this order, one a night.",
            "struct DreamMilestone { u16 dreamt; u16 needs[2]; const u8 *text; };",
            "static const struct DreamMilestone sDreamMilestones[] =", "{"]
    out += ["    { %s, { %s, %s }, sDreamText_%s },   // %s" % (d["flag"], needs[0], needs[1], d["key"].capitalize(), d["after"])
            for d, t, text, needs, boxes in rows]
    out += ["};", "", "#endif // GUARD_DATA_DREAM_LOG_H", ""]
    h = "\n".join(out)
    for d, t, text, needs, boxes in rows:
        print("  %-9s %-28s %s" % (d["key"], t, "  |  ".join("%s (%dpx)" % (l, width(l)) for b in boxes for l in b)))
    for n in notes:
        print("  NOTE " + n)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if h == old:
        print("  dream_log.h is current")
    elif not WRITE:
        print("  dream_log.h would change; pass --write")
    else:
        open(OUT, "w", encoding="utf-8").write(h)
        print("  written  src/data/dream_log.h")


if __name__ == "__main__":
    main()
